    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
                                       
    
        String type = String.valueOf(cmbType.getSelectedItem()).trim();
    String studentId = txtStudentId.getText().trim();
    String lastName = txtLastName.getText().trim();
    String firstName = txtFirstName.getText().trim();
    String ageText = txtAge.getText().trim();
    String sex = String.valueOf(cmbSex.getSelectedItem()).trim();
    String courseYear = txtCourse.getText().trim();
    String emergencyContact = txtEmgName.getText().trim();
    String emergencyContactNumber = txtEmgNum.getText().trim();
    String chiefComplaint = txtComplaint.getText().trim();

    if (lastName.isEmpty() || firstName.isEmpty() || ageText.isEmpty()
            || chiefComplaint.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
            null,
            "Please fill in all required patient information."
        );

        return;
    }

int age;

try {
    age = Integer.parseInt(ageText);

    if (age <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Age must be greater than zero.");
        return;
    }
} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Please enter a valid whole number for age.");
    return;
}

String date = new java.text.SimpleDateFormat("yyyy-MM-dd")
        .format(new java.util.Date());

PatientData patient = new PatientData(
    type,
    studentId,
    lastName,
        firstName,
    age,
    sex,
    courseYear,
    emergencyContact,
    emergencyContactNumber,
    chiefComplaint,
    date
);

try {
    PatientDAO.savePatient(patient);

    javax.swing.JOptionPane.showMessageDialog(
        this, "Patient saved successfully!");

    new Patients().setVisible(true);
    this.dispose();

} catch (java.sql.SQLException ex) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Failed to save patient:\n" + ex.getMessage(),
        "Database Error",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
    ex.printStackTrace();

}
    }//GEN-LAST:event_btnSaveActionPerformed

