    private void btnMedAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMedAddActionPerformed
        String name = txtMedName.getText().trim();
        String category = String.valueOf(cmbCategory.getSelectedItem()).trim();
        String expiryText = txtExpiry.getText().trim();
        if (name.isEmpty() || txtQuantity.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in the medicine name and quantity."); return;
        }
        int qty, lowAt;
        try {
            qty = Integer.parseInt(txtQuantity.getText().trim());
            String low = txtLowStock.getText().trim();
            lowAt = low.isEmpty() ? 5 : Integer.parseInt(low);
            if (qty < 0 || lowAt < 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Quantity and low-stock threshold must be non-negative whole numbers."); return;
        }
        java.sql.Date expiry = null;
        if (!expiryText.isEmpty()) {
            try { expiry = java.sql.Date.valueOf(expiryText); }
            catch (IllegalArgumentException ex) { JOptionPane.showMessageDialog(this, "Enter expiry date as YYYY-MM-DD."); return; }
        }
        try (java.sql.Connection c = DBConnection.getConnection()) {
            c.setAutoCommit(false);
            try {
                int existingId=-1, existingQty=0;
                try(java.sql.PreparedStatement q=c.prepareStatement("SELECT medicine_id,quantity FROM medicines WHERE LOWER(medicine_name)=LOWER(?) ORDER BY medicine_id LIMIT 1")) {
                    q.setString(1,name); try(java.sql.ResultSet r=q.executeQuery()){if(r.next()){existingId=r.getInt(1);existingQty=r.getInt(2);}}
                }
                if(existingId>=0) {
                    try(java.sql.PreparedStatement u=c.prepareStatement("UPDATE medicines SET category=?,expiry_date=?,quantity=?,low_stock_threshold=? WHERE medicine_id=?")) {
                        u.setString(1,category); if(expiry==null)u.setNull(2,java.sql.Types.DATE);else u.setDate(2,expiry);
                        u.setInt(3,existingQty+qty);u.setInt(4,lowAt);u.setInt(5,existingId);u.executeUpdate();
                    }
                } else {
                    try(java.sql.PreparedStatement i=c.prepareStatement("INSERT INTO medicines (medicine_name,category,expiry_date,quantity,low_stock_threshold) VALUES (?,?,?,?,?)")) {
                        i.setString(1,name);i.setString(2,category);if(expiry==null)i.setNull(3,java.sql.Types.DATE);else i.setDate(3,expiry);i.setInt(4,qty);i.setInt(5,lowAt);i.executeUpdate();
                    }
                }
                c.commit();
            } catch(java.sql.SQLException ex) { c.rollback(); throw ex; }
            finally { c.setAutoCommit(true); }
            txtMedName.setText(""); txtQuantity.setText(""); txtExpiry.setText(""); txtLowStock.setText("");
            loadMedicines(); txtMedName.requestFocus();
        } catch(java.sql.SQLException ex) {
            JOptionPane.showMessageDialog(this,"Could not save medicine: " + ex.getMessage(),"Database Error",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnMedAddActionPerformed

    private String statusFor(int qty, int lowAt) {
        if(qty<=0)return "Out of stock";
        if(qty<=lowAt)return "Low stock";
        return "In stock";
    }

    private void loadMedicines() { loadMedicines(""); }
    private void loadMedicines(String search) {
        javax.swing.table.DefaultTableModel model=(javax.swing.table.DefaultTableModel)tblMeds.getModel();
        model.setRowCount(0);
        String sql="SELECT medicine_name,category,quantity,low_stock_threshold,expiry_date FROM medicines WHERE medicine_name LIKE ? OR category LIKE ? ORDER BY medicine_name";
        String q="%"+(search==null?"":search.trim())+"%";
        try(java.sql.Connection c=DBConnection.getConnection();java.sql.PreparedStatement p=c.prepareStatement(sql)) {
            p.setString(1,q);p.setString(2,q);
            try(java.sql.ResultSet r=p.executeQuery()) {
                while(r.next()) { int qty=r.getInt("quantity"),low=r.getInt("low_stock_threshold");java.sql.Date exp=r.getDate("expiry_date");
                    model.addRow(new Object[]{r.getString("medicine_name"),r.getString("category"),qty,statusFor(qty,low),exp==null?"":exp.toString()}); }
            }
            updateCards();
        } catch(java.sql.SQLException ex) { JOptionPane.showMessageDialog(this,"Could not load medicines: " + ex.getMessage(),"Database Error",JOptionPane.ERROR_MESSAGE); }
    }

    private void updateCards() {
        int total=tblMeds.getRowCount(),inStock=0,lowStock=0,outOfStock=0;
        for(int i=0;i<total;i++) { String status=String.valueOf(tblMeds.getValueAt(i,3));
            if(status.equalsIgnoreCase("In stock"))inStock++;else if(status.equalsIgnoreCase("Low stock"))lowStock++;else if(status.equalsIgnoreCase("Out of stock"))outOfStock++; }
        lblTotalMedicines.setText(String.valueOf(total));lblInStock.setText(String.valueOf(inStock));lblLowStock.setText(String.valueOf(lowStock));lblOutOfStock.setText(String.valueOf(outOfStock));
    }


